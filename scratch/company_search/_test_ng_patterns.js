const NG_PATTERNS = [
    /営業[のお]*お断り/,
    /営業[のは]*NG/i,
    /営業[のは]*禁止/,
    /営業[のは]*お控え/,
    /営業[のは]*固くお断り/,
    /営業[^。]{0,20}ご遠慮/,
    /営業[^。]{0,20}お断り/,
    /営業[^。]{0,20}送信しないで/,
    /営業[^。]{0,30}対応しておりません/,
    /営業[^。]{0,30}受け付けておりません/,
    /セールス[のは]*お断り/,
    /セールス[のは]*NG/i,
    /セールス[^。]{0,20}ご遠慮/,
    /セールス[^。]{0,20}お断り/,
    /売[り込]*み[のは]*お断り/,
    /売[り込]*み[のは]*NG/i,
    /売[り込]*み[^。]{0,20}ご遠慮/,
    /売[り込]*み[^。]{0,20}お断り/,
    /売[り込]*み[^。]{0,20}送信しないで/,
    /勧誘[のは]*お断り/,
    /勧誘[^。]{0,20}ご遠慮/,
    /(?:営業|セールス|売り込み).*(?:お断り|NG|ご遠慮)/,
    /(?:営業|セールス).*ご連絡.*(?:ご遠慮|お断り)/,
    /(?:弊社|当社).*営業.*(?:お断り|禁止|NG)/i,
    /(?:営業|セールス|売り込み|ご提案).*目的.*(?:お断り|控えて|ご遠慮|禁止|おりません)/,
    /(?:電話|メール|フォーム).*(?:売り込み|営業|セールス).*(?:お断り|ご遠慮)/,
];

const tests = [
    '※営業メールはご遠慮ください。営業メールへのご返信は対応しておりません。',
    '※こちらのフォームを通しての営業のご連絡はご遠慮ください。',
    '※ 電話やメール、当サイトのフォームを利用した当社への売り込みはお断りしております。',
    '当社への営業の方は当フォームからは送信しないでください。',
    '営業目的のお問い合わせはご遠慮ください。',
];

for (const text of tests) {
    let matched = false;
    for (const p of NG_PATTERNS) {
        const m = text.match(p);
        if (m) {
            console.log('OK  [' + m[0] + '] <- ' + text.substring(0, 40));
            matched = true;
            break;
        }
    }
    if (!matched) {
        console.log('NG! 未検出: ' + text.substring(0, 60));
    }
}
