const EXCLUDE_PATTERNS = [
    /(?:当社|弊社|私共|当店|当院|私達)からの?(?:無理な|しつこい|強引な)?(?:営業|勧誘|セールス|お電話|電話|ご連絡)/,
    /(?:無理な|しつこい|強引な)(?:営業|勧誘|セールス)/,
    /(?:営業|勧誘|セールス).*?(?:一切ありません|いたしません|行いません|しません|致しません)/,
];

const NG_PATTERNS = [
    // 「セールス」という単語が含まれていても、事業名（インサイドセールス事業等）の場合は除外したい
    // 単体の「セールス」は誤検知が多いので、お断り文脈とセットにするか、特定の単語のみにする
    /売り込み/,
    /売込み/,
    /(?:営業|セールス|協業|提案)[^。！？\n]{0,40}(?:お断り|ご遠慮|お控え|禁止|固く|対応できかね|返信(?:いたし)?かね|不要|迷惑|専用フォーム|こちらのフォーム|下記フォーム|こちらより)/,
    /営業(?:メール|電話|目的|関連|関係)/,
    /営業の(?:ご連絡|お問い合わせ|ご案内|ご提案|電話|メール)/,
    /(?:弊社|当社|貴社|当サイト)への(?:営業|セールス|勧誘)/,
    /営業の方/,
    /セールス目的/
];

function testSentence(s) {
    if (EXCLUDE_PATTERNS.some(p => p.test(s))) return "SAFE (Excluded)";
    for (const p of NG_PATTERNS) {
        if (p.test(s)) return "NG";
    }
    return "SAFE";
}

